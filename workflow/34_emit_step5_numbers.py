#!/usr/bin/env python3
"""Emit writing_outputs/drafts/step5_numbers.tex -- one LaTeX macro per Step-5 number.

Why this exists
---------------
Every number in the manuscript's Step-5 sections is defined here and nowhere else, so
the prose cannot drift from the artefacts. Hand-transcribing ~60 figures from four JSON
files into 3,000 lines of LaTeX is the single most likely way to publish a wrong number,
and it is entirely avoidable.

A macro whose source artefact is missing is emitted as a loud
``\textbf{[PENDING]}'' rather than as a plausible default, so an unfinished pipeline
shows up as a visible hole in the PDF instead of a silently wrong figure.
"""
from __future__ import annotations

from repo_paths import REPO_ROOT

import json
import pathlib
import sys

ROOT = pathlib.REPO_ROOT
RESULTS = ROOT / "results"
OUT = ROOT / "writing_outputs" / "drafts" / "step5_numbers.tex"

PENDING = r"\textbf{[PENDING]}"
lines: list[str] = []
missing: list[str] = []


def load(name: str) -> dict | None:
    p = RESULTS / name
    if not p.exists():
        missing.append(name)
        return None
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except Exception as exc:                                  # noqa: BLE001
        missing.append(f"{name} ({exc})")
        return None


def emit(macro: str, value, fmt: str = "{:.4f}") -> None:
    """Define \\<macro>. None -> a visible PENDING marker."""
    if value is None:
        body = PENDING
    elif isinstance(value, bool):
        body = "yes" if value else "no"
    elif isinstance(value, (int,)) and not isinstance(value, bool):
        body = f"{value:,}".replace(",", "{,}")
    elif isinstance(value, float):
        body = fmt.format(value)
    else:
        body = str(value)
    lines.append(rf"\newcommand{{\{macro}}}{{{body}}}")


def get(d: dict | None, *path, default=None):
    cur = d
    for k in path:
        if cur is None:
            return default
        if isinstance(cur, dict):
            cur = cur.get(k)
        else:
            return default
    return cur if cur is not None else default


def signed(v, nd: int = 4) -> str | None:
    return None if v is None else f"{v:+.{nd}f}"


# ======================================================================= sources
stack = load("step5_cluster_weights.json")
boot = load("step5_bootstrap_ci.json")
loop = load("step5_agentic_loop_log.json")
ver = load("step5_verification_report.json")
gnn = load("step5_gnn_training.json")
graph = load("step5_graph_report.json")
folds = load("step5_lcgo_folds.json")
smoke = load("step5_clusterscore_smoke.json")

lines.append("% Generated by workflow/34_emit_step5_numbers.py -- do not edit by hand.")

# ------------------------------------------------------------------- headline
emit("SFiveHeadline", get(stack, "val_total_at_frozen_weights"), "{:.6f}")
emit("SFiveOOF", get(stack, "oof_total_at_frozen_weights"), "{:.6f}")
emit("SFiveValTuned", get(stack, "val_total_val_tuned_OPTIMISTIC"), "{:.6f}")
emit("SFiveMarginBench", signed(get(stack, "margin_vs_benchmark")))
emit("SFiveMarginFour", signed(get(stack, "margin_vs_step4")))
emit("SFiveGapOofVal", signed(get(stack, "generalisation_gap_oof_to_val")))
emit("SFiveBeatsBench", get(stack, "beats_benchmark"))
emit("SFiveBeatsFour", get(stack, "beats_step4"))
emit("SFiveTargetMet", get(stack, "target_0_4850_met"))

# ------------------------------------------------------------- ablation ladder
lad = get(stack, "ablation_ladder", default={}) or {}
emit("SFiveRungZero", lad.get("rung0_step4_scalar_inner_cohort"), "{:.6f}")
emit("SFiveRungOne", lad.get("rung1_scalar_oof_cohort"), "{:.6f}")
emit("SFiveRungTwo", lad.get("rung2_cluster_oof_cohort"), "{:.6f}")
emit("SFiveGainCrossfit", signed(lad.get("gain_from_cross_fitting_alone")))
emit("SFiveGainCluster", signed(lad.get("gain_from_the_cluster_extension")))

# -------------------------------------------------------------- selected model
emit("SFiveClusterCol", get(stack, "selected", "cluster_column"))
nC = get(stack, "selected", "n_clusters")
emit("SFiveNClusters", int(nC) if nC is not None else None)
emit("SFiveAlpha", get(stack, "selected", "alpha"), "{:.3f}")
roles = get(stack, "roles")
emit("SFiveNRoles", len(roles) if roles else None)
emit("SFiveRoles", ", ".join(r.replace("_", r"\_") for r in roles) if roles else None)
dropped = get(stack, "roles_dropped")
emit("SFiveRolesDropped",
     (", ".join(r.replace("_", r"\_") for r in dropped) if dropped else "none")
     if dropped is not None else None)
emit("SFiveNParams",
     (4 * len(roles) * int(nC)) if (roles and nC is not None) else None)
emit("SFiveNParamsScalar", (4 * len(roles)) if roles else None)

# ------------------------------------------------------- stacked module scores
MODS = [("MOne", "m1_abundance"), ("MTwo", "m2_fold_change"),
        ("MSOne", "m3_s1_chem"), ("MSTwo", "m3_s2_strain"),
        ("MSThree", "m3_s3_both"), ("MTime", "m3_time"), ("MFour", "m4_dep")]
ms = get(stack, "module_scores", default={}) or {}
for suffix, key in MODS:
    for tag, prefix in (("val:cluster_oof_frozen", "SFiveVal"),
                        ("val:scalar_oof_frozen", "SFiveScal"),
                        ("oof:cluster_frozen", "SFiveOofCl")):
        emit(prefix + suffix, get(ms, tag, key))
    # The clean A/B per module: cluster rung minus scalar rung on the same cohort with
    # the same members. This is the column the paper's central claim rests on, so it is
    # computed here from the artefact rather than differenced by hand in the LaTeX.
    a = get(ms, "val:cluster_oof_frozen", key)
    b = get(ms, "val:scalar_oof_frozen", key)
    emit("SFiveDiff" + suffix,
         signed(a - b) if isinstance(a, float) and isinstance(b, float) else None)
# member totals, for the members table
tot = get(stack, "totals", default={}) or {}
# LaTeX control words are letters only: "\SFiveValTotGbdtmol3d" would parse as
# "\SFiveValTotGbdtmol" followed by the characters "3d", silently colliding with the
# gbdt_mol macro. Role suffixes are therefore spelled out in letters.
ROLE_SUFFIX = {
    "gbdt_tab": "Gbdttab",
    "gbdt_mol": "Gbdtmol",
    "gbdt_mol3d": "GbdtmolThreeD",
    "bench": "Bench",
    "gnn": "Gnn",
    "dl": "Dl",
}
for role, cam in ROLE_SUFFIX.items():
    emit("SFiveValTot" + cam, tot.get("val:" + role), "{:.4f}")
    emit("SFiveOofTot" + cam, tot.get("oof:" + role), "{:.4f}")
emit("SFiveValTotCluster", tot.get("val:cluster_oof_frozen"), "{:.6f}")
emit("SFiveValTotScalar", tot.get("val:scalar_oof_frozen"), "{:.6f}")

# ------------------------------------------------------------------- bootstrap
bvs = get(boot, "cluster_frozen_vs_scalar_frozen", default={}) or {}
ci = (bvs.get("diff_ci95") or bvs.get("ci95") or bvs.get("ci_95")
      or bvs.get("percentile_ci95"))
if isinstance(ci, (list, tuple)) and len(ci) == 2:
    emit("SFiveBootLo", float(ci[0]), "{:+.4f}")
    emit("SFiveBootHi", float(ci[1]), "{:+.4f}")
else:
    emit("SFiveBootLo", None)
    emit("SFiveBootHi", None)
emit("SFiveBootMean", signed(bvs.get("diff_mean")))
emit("SFiveBootSD", bvs.get("diff_sd"))
frac = bvs.get("frac_bootstrap_replicates_favouring_a")
emit("SFiveBootFrac", (100.0 * frac) if isinstance(frac, (int, float)) else None,
     "{:.1f}")
emit("SFiveBootN", get(boot, "cluster_frozen_vs_scalar_frozen", "n_boot") or
     get(boot, "n_boot") or 1000)

# ----------------------------------------------------------------- agentic loop
emit("SFiveLoopIters", get(loop, "n_iterations"))
emit("SFiveLoopAccepted", get(loop, "n_accepted"))
emit("SFiveLoopCrashes", get(loop, "n_crashes"))
pf = get(loop, "pareto_front")
emit("SFiveParetoSize", len(pf) if isinstance(pf, list) else None)
emit("SFiveLoopBestOof", get(loop, "best", "oof_exact_total"), "{:.6f}")
emit("SFiveLoopBestCol", get(loop, "best", "cluster_column") or
     get(loop, "best", "cluster_col") or
     get(loop, "best", "config", "cluster_column"))
emit("SFiveLoopPromoted", get(ver, "headline", "loop_state_promoted"))
emit("SFiveLoopHeadline", get(ver, "headline", "val_total") or
     get(ver, "headline", "headline_val_total"), "{:.6f}")

# ------------------------------------------------------------------- test export
emit("SFiveTestRows", get(ver, "test_export", "n_rows") or
     get(ver, "export", "n_rows"))
emit("SFiveTestPCC", get(ver, "test_export", "indicative_delta_pcc") or
     get(ver, "indicative_delta_pcc"), "{:.4f}")
nchk = get(ver, "n_checks")
npass = get(ver, "n_passed")
emit("SFiveVerChecks", int(nchk) if nchk is not None else None)
emit("SFiveVerPassed", int(npass) if npass is not None else None)
ncrit = get(ver, "n_criteria")
ncritmet = get(ver, "n_criteria_met")
emit("SFiveCritTotal", int(ncrit) if ncrit is not None else None)
emit("SFiveCritMet", int(ncritmet) if ncritmet is not None else None)

# --------------------------------------------------------------------- network
folds_g = get(gnn, "folds", default=None)
if isinstance(folds_g, dict) and folds_g:
    folds_g = [folds_g[k] for k in sorted(folds_g)]
if isinstance(folds_g, list) and folds_g:
    npar = folds_g[0].get("n_parameters")
    eps = [f.get("best_epoch") or f.get("epoch") for f in folds_g]
    eps = [e for e in eps if isinstance(e, int)]
    pccs = [f.get("best_dev_pcc") if isinstance(f.get("best_dev_pcc"), float)
            else f.get("dev_pcc") for f in folds_g]
    pccs = [x for x in pccs if isinstance(x, float)]
    emit("SFiveGnnParams", int(npar) if npar else None)
    emit("SFiveGnnEpochMedian", int(sorted(eps)[len(eps) // 2]) if eps else None)
    emit("SFiveGnnDevPcc", (sum(pccs) / len(pccs)) if pccs else None)
else:
    for m in ("SFiveGnnParams", "SFiveGnnEpochMedian", "SFiveGnnDevPcc"):
        emit(m, None)
emit("SFiveLambdaControl",
     signed(get(gnn, "lambda_graph_control_fold0", "delta_from_penalty")
            or get(gnn, "lambda_graph_control", "delta_from_penalty"), 4))

# ------------------------------------------------- already-computed provenance
emit("SFiveStringEdges", int(get(graph, "n_edges_undirected", default=0)) or None)
emit("SFiveStringMapped", int(get(graph, "n_mapped_to_string", default=0)) or None)
emit("SFiveGiant", int(get(graph, "spectral", "giant_component_size", default=0)) or None)
emit("SFiveJaccard", get(graph, "string_vs_coresponse_jaccard"), "{:.4f}")
emit("SFiveCoEdges", int(get(graph, "coresponse_graph", "n_edges_undirected",
                            default=0)) or None)
emit("SFiveSecPerEval", get(smoke, "check3_seconds_per_evaluation"), "{:.4f}")
emit("SFiveHarnessSec", get(smoke, "exact_harness_seconds_per_evaluation_for_scale"),
     "{:.1f}")
mix = get(folds, "overall_regime_mix", default={}) or {}
for k, macro in (("full", "SFiveMixFull"), ("chem_novel", "SFiveMixChem"),
                 ("strain_novel", "SFiveMixStrain"), ("both_novel", "SFiveMixBoth")):
    emit(macro, int(mix[k]) if k in mix else None)

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")

n_pending = sum(1 for ln in lines if PENDING in ln)
print(f"wrote {OUT}")
print(f"  {len(lines) - 1} macros, {n_pending} PENDING")
if missing:
    print("  missing artefacts: " + ", ".join(missing))
if n_pending:
    print("  NOTE: PENDING macros render as a visible marker, never as a number.")
sys.exit(0)
