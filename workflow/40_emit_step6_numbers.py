PENDING = r"\textbf{[PENDING]}"
lines: list[str] = []
missing: list[str] = []


def load(name: str) -> dict | None:
    p = RESULTS / name
    if not p.exists():
        missing.append(name)
        return None
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except Exception as exc:                                          # noqa: BLE001
        missing.append(f"{name} ({exc})")
        return None


def emit(macro: str, value, fmt: str = "{:.4f}") -> None:
    if value is None:
        body = PENDING
    elif isinstance(value, bool):
        body = "yes" if value else "no"
    elif isinstance(value, int):
        body = f"{value:,}".replace(",", "{,}")
    elif isinstance(value, float):
        body = fmt.format(value)
    else:
        body = str(value)
    lines.append(rf"\newcommand{{\{macro}}}{{{body}}}")


def get(d, *path, default=None):
    cur = d
    for k in path:
        if cur is None:
            return default
        if isinstance(cur, dict):
            cur = cur.get(k)
        elif isinstance(cur, list) and isinstance(k, int):
            cur = cur[k] if -len(cur) <= k < len(cur) else None
        else:
            return default
    return cur if cur is not None else default


def signed(v, nd: int = 4) -> str | None:
    return None if v is None else f"{v:+.{nd}f}"


def sci(v, nd: int = 2) -> str | None:
    r"""Format as LaTeX scientific notation, e.g. 4.88\times 10^{-6}.

    Emitting ``{:.2e}`` directly gives "4.88e-06", which inside math mode renders the
    exponent's minus sign as a binary operator and reads as "4.88e - 06". These macros are
    always used in math mode, so the mantissa/exponent form is produced here.
    """
    if v is None:
        return None
    s = f"{float(v):.{nd}e}"
    mant, exp = s.split("e")
    e = int(exp)
    if e == 0:
        return mant
    return rf"{mant}\times 10^{{{e}}}"


def tex(s) -> str | None:
    """Escape the LaTeX specials that occur in our identifiers."""
    if s is None:
        return None
    return str(s).replace("_", r"\_").replace("%", r"\%").replace("&", r"\&")


