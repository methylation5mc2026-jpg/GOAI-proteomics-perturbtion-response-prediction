def potency(compound: str, protein: str):
    rec = _POS.get(compound)
    if not rec:
        return None
    for h in rec.get("hits", []):
        if h.get("protein") == protein and h.get("status") == "annotated":
            return float(h.get("pactivity"))
    return None


