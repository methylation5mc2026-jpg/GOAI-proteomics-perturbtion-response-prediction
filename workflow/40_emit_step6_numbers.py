"""Emit writing_outputs/drafts/step6_numbers.tex -- one LaTeX macro per Step-6 number.

Why this exists
---------------
Same contract as ``34_emit_step5_numbers.py``: every Step-6 quantity that appears in the
manuscript is defined here, read from a result artefact, and nowhere else. The prose
cannot drift from the pipeline because the prose does not contain any numbers.

A macro whose source artefact is missing or whose key is absent is emitted as a loud
``\\textbf{[PENDING]}`` marker, so an unfinished pipeline shows up as a visible hole in
the PDF rather than as a silently wrong or stale figure.
"""
from __future__ import annotations

